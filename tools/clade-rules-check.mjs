for (const [sci, de, bands, why] of SAMPLES) {
  if (!CHAINS_RAW[sci]) { note("S", `${sci}: keine eingebettete Kette.`); sFail++; continue; }
  const res = applyCladeRules(chainOf(sci), "species");
  const bad = [];
  for (const [gene, band] of Object.entries(bands)) {
    const v = res.genome[GENE_INDEX[gene]];
    let ok;
    if (v === null) ok = false;
    else if (band[0] === ">") ok = v > band[1];
    else if (band[0] === "<") ok = v < band[1];
    else ok = v >= band[1] && v <= band[2];
    if (!ok) {
      const want = band[0] === "[]" ? `[${band[1]}, ${band[2]}]` : `${band[0]} ${band[1]}`;
      bad.push(`${gene}=${fmt(v)} (erwartet ${want})`);
    }
  }
  const top = res.matched[0];
  if (bad.length) {
    sFail++;
    note("S", `${de} (${sci}): ${bad.join(", ")} · ${why}`);
    console.log(`  ✗ ${de.padEnd(30)} ${String(res.count).padStart(2)}/25 Gene · spezifischste Regel: ${top ? top.sci : "—"}`);
  } else {
    sPass++;
    console.log(`  ✓ ${de.padEnd(30)} ${String(res.count).padStart(2)}/25 Gene · spezifischste Regel: ${top ? top.sci : "—"}`);
  }
}
