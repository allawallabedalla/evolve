// G1 — Gen-Liste gegen app/archetypes.js
{
  const w = {};
  new Function("window", readFileSync(join(ROOT, "app", "archetypes.js"), "utf-8"))(w);
  const archGenes = w.ARCHETYPES.genes;
  if (JSON.stringify(archGenes) !== JSON.stringify(GENES))
    note("G1", "GENES weicht von app/archetypes.js ab — jede abgeleitete Position waere verdreht.");
}

// ---------------------------------------------------------------------------
// G2/G3/R1 — Form und Begruendung jeder Regel
const qidOwner = new Map();
for (const r of CLADE_RULES) {
  const at = `Regel ${r.sci || "?"}`;
  const qids = Array.isArray(r.qid) ? r.qid : [r.qid];
  if (!qids.length) note("G2", `${at}: keine QID.`);
  for (const q of qids) {
    if (!/^Q[1-9][0-9]*$/.test(q)) note("G2", `${at}: „${q}“ ist keine QID im Q-Format.`);
    if (qidOwner.has(q)) note("G3", `${at}: QID ${q} steht schon in „${qidOwner.get(q)}“.`);
    else qidOwner.set(q, r.sci);
  }
  if (typeof r.level !== "number" || !Number.isFinite(r.level))
    note("G2", `${at}: Feld „level“ fehlt oder ist keine Zahl.`);
  const entries = Object.entries(r.genes || {});
  if (!entries.length) note("G2", `${at}: setzt kein einziges Gen.`);
  for (const [gene, v] of entries) {
    if (GENE_INDEX[gene] === undefined) note("G2", `${at}: unbekanntes Gen „${gene}“.`);
    if (typeof v !== "number" || !(v >= 0 && v <= 1))
      note("G2", `${at}: Wert fuer „${gene}“ ist ${v} — ausserhalb [0,1].`);
  }
  // R1 — die Begruendungspflicht des Repos. 60 Zeichen ist kein Selbstzweck: kuerzer
  // laesst sich ein WARUM nicht formulieren, und ein „weil Saeugetier“ waere genau
  // die Tautologie, die dieser Prüfstand verhindern soll.
  if (!r.reason || r.reason.trim().length < 60)
    note("R1", `${at}: keine oder zu knappe Begruendung.`);
}

// ---------------------------------------------------------------------------
// R2 — alle Wurzel-Kladen der Ernte abgedeckt (gegen die Quelldatei geprueft)
{
  const src = readFileSync(join(ROOT, "tools", "wikidata-harvest.mjs"), "utf-8");
  const block = src.match(/const ROOTS = \[[\s\S]*?\n\];/);
  if (!block) note("R2", "ROOTS in tools/wikidata-harvest.mjs nicht gefunden.");
  else {
    const roots = [...block[0].matchAll(/\["(Q\d+)",\s*"([^"]+)"\]/g)].map((m) => [m[1], m[2]]);
    if (roots.length !== 25)
      console.log(`  Hinweis: ${roots.length} Wurzel-Kladen in der Ernte (erwartet waren 25).`);
    for (const [qid, label] of roots)
      if (!qidOwner.has(qid)) note("R2", `Wurzel-Klade ${qid} (${label}) hat keine Regel.`);
  }
}

// ---------------------------------------------------------------------------
// R3 — Spezifitaets-Ordnung gegen echte Ketten
{
  const seen = new Set();
  for (const name of CHAIN_NAMES) {
    const chain = chainOf(name);
    // Position jeder Regel in DIESER Kette (klein = spezifisch, weil Art zuerst).
    const pos = [];
    chain.forEach((q, i) => {
      for (const r of CLADE_RULES) {
        const qs = Array.isArray(r.qid) ? r.qid : [r.qid];
        if (qs.includes(q)) pos.push({ rule: r, i });
      }
    });
    for (let a = 0; a < pos.length; a++) {
      for (let b = a + 1; b < pos.length; b++) {
        const spec = pos[a], gen = pos[b];             // spec liegt naeher an der Art
        if (spec.rule === gen.rule) continue;          // dieselbe Regel ueber zwei QIDs
        if (spec.rule.level > gen.rule.level) continue; // korrekt geordnet
        const key = `${spec.rule.sci}|${gen.rule.sci}`;
        if (seen.has(key)) continue;
        seen.add(key);
        note("R3", `„${spec.rule.sci}“ (level ${spec.rule.level}) liegt in der Kette von `
          + `${name} UNTER „${gen.rule.sci}“ (level ${gen.rule.level}) — die spezifischere `
          + `Klade muss das hoehere level tragen, sonst gewinnt bei Konflikt die falsche.`);
      }
    }
  }
}

// ---------------------------------------------------------------------------
// R4/R5 — Determinismus, Reihenfolge-Unabhaengigkeit, Konfidenz
{
  for (const name of CHAIN_NAMES) {
    const c = chainOf(name);
    const a = applyCladeRules(c, "species");
    const b = applyCladeRules(c, "species");
    const rev = applyCladeRules([...c].reverse(), "species");
    if (JSON.stringify(a.genome) !== JSON.stringify(b.genome))
      note("R4", `${name}: zwei Aufrufe liefern verschiedene Genome.`);
    if (JSON.stringify(a.genome) !== JSON.stringify(rev.genome))
      note("R4", `${name}: umgedrehte Kette liefert ein anderes Genom — die Zuordnung `
        + "haengt faelschlich an der Reihenfolge.");
    for (let g = 0; g < GENES.length; g++) {
      const set = a.genome[g] !== null;
      if (set && a.conf[g] !== 2) note("R5", `${name}: Gen ${GENES[g]} traegt Konfidenz ${a.conf[g]} statt 2.`);
      if (!set && a.conf[g] !== null) note("R5", `${name}: Gen ${GENES[g]} ohne Wert traegt eine Konfidenz.`);
      if (set && !(a.genome[g] >= 0 && a.genome[g] <= 1))
        note("R5", `${name}: Gen ${GENES[g]} = ${a.genome[g]} ausserhalb [0,1].`);
    }
  }
}

