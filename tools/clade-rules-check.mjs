// --online — sind die eingebetteten Ketten noch aktuell?
if (ONLINE) {
  const UA = "evolve-artenkatalog/0.1 (https://github.com/allawallabedalla/evolve)";
  const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
  let last = 0;
  // Hoeflichkeitsabstand und exponentielles Zurueckziehen wie in tools/build-catalog.mjs
  // (dort gemessen: ohne Drosselung laeuft ein Lauf mit Elterntaxon-Ketten zuverlaessig
  // in ein 429). Hier grosszuegiger, weil eine Kette bis zu 45 Anfragen kostet.
  async function api(url, a = 0) {
    const w = last + 250 - Date.now(); if (w > 0) await sleep(w); last = Date.now();
    let r;
    try { r = await fetch(url, { headers: { "User-Agent": UA } }); }
    catch (e) { if (a < 6) { await sleep(2000 * 2 ** a); return api(url, a + 1); } throw e; }
    if ((r.status === 429 || r.status >= 500) && a < 6) { await sleep(2000 * 2 ** a); return api(url, a + 1); }
    if (!r.ok) throw new Error("HTTP " + r.status);
    return r.json();
  }
  // Nur eine Teilmenge und nur die Stichproben-Arten: eine Kette kostet bis zu 45
  // Anfragen, alle 116 waeren ueber 4000 — das waere gegenueber der API unhoeflich
  // und fuer den Zweck (merkt jemand, wenn Wikidata ein Elterntaxon umhaengt?) unnoetig.
  // Wer alles pruefen will, ruft mit --online-all auf.
  const ALL = process.argv.includes("--online-all");
  const toCheck = ALL ? CHAIN_NAMES : SAMPLES.map((s) => s[0]);
  console.log(`\n--online: ${toCheck.length} eingebettete Ketten gegen Wikidata pruefen …`);
  let drift = 0, ruleQids = 0;
  for (const name of toCheck) {
    const chain = chainOf(name);
    // Nur die QIDs, auf denen wirklich eine Regel sitzt — alles andere geht in die
    // Zuordnung gar nicht ein, eine Abweichung dort waere folgenlos.
    const relevant = chain.filter((q) => CLADE_RULES.some(
      (r) => (Array.isArray(r.qid) ? r.qid : [r.qid]).includes(q)));
    ruleQids += relevant.length;
    const fresh = new Set();
    let cur = chain[0], guard = 0;
    try {
      while (cur && guard++ < 45) {
        fresh.add(cur);
        const d = await api(`https://www.wikidata.org/w/api.php?action=wbgetentities&ids=${cur}`
          + "&props=claims&format=json");
        cur = d.entities?.[cur]?.claims?.P171?.[0]?.mainsnak?.datavalue?.value?.id || null;
      }
    } catch (err) {
      // Ein Netzfehler ist kein Regelwerk-Fehler: melden, aber den Prüfstand nicht
      // rot faerben — sonst haengt ein Gate an der Verfuegbarkeit einer fremden API.
      console.log(`  ! ${name}: Kette nicht abrufbar (${err.message}) — uebersprungen.`);
      continue;
    }
    const lost = relevant.filter((q) => !fresh.has(q));
    if (lost.length) {
      drift++;
      note("ONLINE", `${name}: diese Regel-QIDs stehen nicht mehr in der Wikidata-Kette: `
        + `${lost.join(", ")} — die eingebettete Kette ist veraltet oder die Regel greift nicht mehr.`);
    }
  }
  console.log(`  ${toCheck.length} Ketten neu geholt, ${ruleQids} Regel-Treffer nachgeprueft, `
    + `${drift} mit Abweichung.`);
}

